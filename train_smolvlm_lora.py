#!/usr/bin/env python3
"""Parameter-efficient SmolVLM2 adaptation on OrnaScout structured targets.

Designed for a CUDA Colab/workstation. The training file must be generated by
``ornascout_pipeline_v2.py prepare``. Only train-split source images appear in
that file, preventing tile leakage into validation or test evaluation.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from PIL import Image


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--train", type=Path, required=True)
    parser.add_argument("--model-id", default="HuggingFaceTB/SmolVLM2-2.2B-Instruct")
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--epochs", type=float, default=2.0)
    parser.add_argument("--batch-size", type=int, default=1)
    parser.add_argument("--grad-accum", type=int, default=8)
    parser.add_argument("--learning-rate", type=float, default=2e-4)
    parser.add_argument("--lora-r", type=int, default=16)
    parser.add_argument("--lora-alpha", type=int, default=32)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--limit", type=int)
    args = parser.parse_args()

    try:
        import torch
        from datasets import Dataset
        from peft import LoraConfig
        from transformers import AutoModelForImageTextToText, AutoProcessor, TrainingArguments, Trainer
    except ImportError as exc:
        raise SystemExit("Install requirements.txt in a CUDA environment") from exc

    examples = read_jsonl(args.train)
    if args.limit:
        examples = examples[: args.limit]
    dataset = Dataset.from_list(examples)
    processor = AutoProcessor.from_pretrained(args.model_id)
    processor.tokenizer.padding_side = "right"
    model = AutoModelForImageTextToText.from_pretrained(
        args.model_id,
        torch_dtype=torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16,
        device_map="auto",
    )
    model = __import__("peft").get_peft_model(model, LoraConfig(
        r=args.lora_r,
        lora_alpha=args.lora_alpha,
        lora_dropout=0.05,
        bias="none",
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj"],
        task_type="CAUSAL_LM",
    ))
    model.config.use_cache = False
    model.gradient_checkpointing_enable()

    class Collator:
        def __call__(self, batch: list[dict[str, Any]]) -> dict[str, Any]:
            prompts, texts, images = [], [], []
            for item in batch:
                user = {"role": "user", "content": [{"type": "image"}, {"type": "text", "text": item["prompt"]}]}
                messages = [
                    user,
                    {"role": "assistant", "content": [{"type": "text", "text": json.dumps(item["target"])}]},
                ]
                prompts.append(processor.apply_chat_template([user], add_generation_prompt=True))
                texts.append(processor.apply_chat_template(messages, add_generation_prompt=False))
                images.append(Image.open(item["image_path"]).convert("RGB"))
            encoded = processor(text=texts, images=images, padding=True, return_tensors="pt")
            prompt_encoded = processor(text=prompts, images=images, padding=True, return_tensors="pt")
            labels = encoded["input_ids"].clone()
            labels[labels == processor.tokenizer.pad_token_id] = -100
            prompt_lengths = prompt_encoded["attention_mask"].sum(dim=1).tolist()
            for row, prompt_length in enumerate(prompt_lengths):
                labels[row, : int(prompt_length)] = -100
            encoded["labels"] = labels
            return encoded

    training_args = TrainingArguments(
        output_dir=str(args.out_dir),
        num_train_epochs=args.epochs,
        per_device_train_batch_size=args.batch_size,
        gradient_accumulation_steps=args.grad_accum,
        learning_rate=args.learning_rate,
        warmup_ratio=0.05,
        weight_decay=0.01,
        logging_steps=10,
        save_strategy="epoch",
        bf16=torch.cuda.is_bf16_supported(),
        fp16=not torch.cuda.is_bf16_supported(),
        remove_unused_columns=False,
        report_to="none",
        seed=args.seed,
        data_seed=args.seed,
    )
    trainer = Trainer(model=model, args=training_args, train_dataset=dataset, data_collator=Collator())
    trainer.train()
    trainer.save_model(str(args.out_dir / "final_adapter"))
    processor.save_pretrained(str(args.out_dir / "final_adapter"))


if __name__ == "__main__":
    main()
